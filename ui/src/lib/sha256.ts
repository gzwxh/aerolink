const HASH_BYTES = 32

function rotr(value: number, bits: number): number {
  return (value >>> bits) | (value << (32 - bits))
}

export function readUint32(bytes: Uint8Array, offset: number): number {
  return (
    ((bytes[offset] << 24) | (bytes[offset + 1] << 16) | (bytes[offset + 2] << 8) | bytes[offset + 3]) >>>
    0
  )
}

export function writeUint32(bytes: Uint8Array, offset: number, value: number): void {
  bytes[offset] = (value >>> 24) & 0xff
  bytes[offset + 1] = (value >>> 16) & 0xff
  bytes[offset + 2] = (value >>> 8) & 0xff
  bytes[offset + 3] = value & 0xff
}

export function sha256(message: Uint8Array): Uint8Array {
  const bitLength = message.length * 8
  const paddedLength = ((message.length + 8) >> 6 << 6) + 64
  const block = new Uint8Array(paddedLength)
  block.set(message)
  block[message.length] = 0x80
  writeUint32(block, paddedLength - 8, Math.floor(bitLength / 0x100000000))
  writeUint32(block, paddedLength - 4, bitLength >>> 0)

  const hash = new Uint32Array([
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
  ])
  const w = new Uint32Array(64)

  for (let offset = 0; offset < paddedLength; offset += 64) {
    for (let i = 0; i < 16; i += 1) {
      w[i] = readUint32(block, offset + i * 4)
    }
    for (let i = 16; i < 64; i += 1) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3)
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10)
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0
    }

    let a = hash[0]
    let b = hash[1]
    let c = hash[2]
    let d = hash[3]
    let e = hash[4]
    let f = hash[5]
    let g = hash[6]
    let h = hash[7]

    for (let i = 0; i < 64; i += 1) {
      const s1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25)
      const ch = (e & f) ^ (~e & g)
      const t1 = (h + s1 + ch + SHA256_K[i] + w[i]) >>> 0
      const s0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22)
      const maj = (a & b) ^ (a & c) ^ (b & c)
      const t2 = (s0 + maj) >>> 0
      h = g
      g = f
      f = e
      e = (d + t1) >>> 0
      d = c
      c = b
      b = a
      a = (t1 + t2) >>> 0
    }

    hash[0] = (hash[0] + a) >>> 0
    hash[1] = (hash[1] + b) >>> 0
    hash[2] = (hash[2] + c) >>> 0
    hash[3] = (hash[3] + d) >>> 0
    hash[4] = (hash[4] + e) >>> 0
    hash[5] = (hash[5] + f) >>> 0
    hash[6] = (hash[6] + g) >>> 0
    hash[7] = (hash[7] + h) >>> 0
  }

  const digest = new Uint8Array(HASH_BYTES)
  for (let i = 0; i < hash.length; i += 1) {
    writeUint32(digest, i * 4, hash[i])
  }
  return digest
}

const HMAC_BLOCK_BYTES = 64

export function hmacSha256(key: Uint8Array, message: Uint8Array): Uint8Array {
  const inner = new Uint8Array(HMAC_BLOCK_BYTES)
  const outer = new Uint8Array(HMAC_BLOCK_BYTES)
  const paddedKey = key.length > HMAC_BLOCK_BYTES ? sha256(key) : key
  inner.set(paddedKey)
  outer.set(paddedKey)
  for (let i = 0; i < HMAC_BLOCK_BYTES; i += 1) {
    inner[i] ^= 0x36
    outer[i] ^= 0x5c
  }

  const innerDigest = sha256(concatBytes([inner, message]))
  return sha256(concatBytes([outer, innerDigest]))
}

export function concatBytes(parts: Uint8Array[]): Uint8Array<ArrayBuffer> {
  const output = new Uint8Array(parts.reduce((sum, part) => sum + part.length, 0))
  let offset = 0
  for (const part of parts) {
    output.set(part, offset)
    offset += part.length
  }
  return output
}
